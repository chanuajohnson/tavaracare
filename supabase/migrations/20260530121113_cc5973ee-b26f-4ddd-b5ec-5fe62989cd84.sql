Today is Indian Arrival Day. The street is quiet. Most offices are closed. In a house in Diego Martin, a daughter is still turning her mother in bed at 7am, because the schedule does not know it is a holiday. In a house in San Fernando, a care professional is on her third public holiday this year, and she is wondering whether to ask about her pay.

This is the part of caregiving nobody talks about. The care does not pause for a holiday. The people doing the care do not get a free day. And the rules that protect them are written down, but most families and most care professionals have never read them together.

So let us read them together.

## What the law actually says

The Ministry of Labour's Minimum Wages Order is clear. A worker who works on a public holiday in Trinidad and Tobago is entitled to **double time** for the hours worked. That is 2x the normal hourly rate. The national minimum wage itself is $20.50 per hour. For care professionals, who usually earn well above minimum wage, the principle is the same: the hourly rate doubles for the holiday hours.

If the public holiday falls on a day the care professional would normally have been working, she is also entitled to her normal day's pay in addition. If it falls on her usual day off and she still comes in, she is entitled to double time for the hours worked.

This is not a Tavara policy. It is national law. Most families do not know it. Most care professionals know it but find it hard to bring up. Let us make it easier on both sides.

## From the family side

You are not a bad family because you forgot the holiday was coming. Most families do. The fix is not guilt. The fix is planning.

**Plan two weeks ahead, not the night before.** Sit with your care team in the second week of every month and look at the next month's calendar. Mark the public holidays in red. Decide now who is covering each one. A care professional who knows three weeks early that she is working Indian Arrival Day can plan her own family around it. A care professional who finds out the night before is being asked to sacrifice her holiday twice, once for your loved one and once for her own.

**Decide who covers when your main care professional wants the day off.** This is what a fill-in care professional is for. If your care arrangement has one person and no backup, the first public holiday will tell you. Build the rotation before you need it, not after.

**Pay the double time without being asked.** This is the single biggest trust signal a family can give. When the payroll for the holiday week comes around, the holiday hours are already at the doubled rate. The care professional does not have to ask. She did not have to choose between her job and the conversation she did not want to have.

**Mind the small dignities.** A plate from the family Pelau. A ride home after dark if shifts run long. A thank you that is spoken out loud, not just felt. These cost nothing and they hold a care team together for years.

**Put the holiday rule in writing once.** In the care arrangement document, one paragraph. Public holidays are paid at double time. Coverage is planned by the second week of the prior month. Swaps are agreed in writing. Once it is on paper, you never have to negotiate it again.

## From the care professional side

The double time on a public holiday is your right. It is not a favour the family is doing. Asking for it is not greed. Not asking for it teaches the family that the rule does not apply to your household, and a year from now you will be quietly working five public holidays at flat rate.

**Ask early, not on the day.** If you know a holiday is coming, raise it at the planning conversation two weeks before. "I am happy to work the holiday. As you know, the rate doubles for those hours. I just want us both to be ready for it." That is the whole script. It is calm. It is professional. It treats the family as a partner, not an opponent.

**Know when to accept a swap.** Sometimes a family asks if you would rather take a different day off in exchange for working the holiday at the normal rate. That is your choice, not the law. If the swap suits your own family, take it. If it does not, the law is on your side and double time applies.

**Professionalism still applies on the holiday.** The 8-hour shift is the 8-hour shift. The no-personal-phone policy still holds. Carnival is not in the bedroom. Divali sweets are kindness, not a reason to step away from the loved one for an hour. The pay doubles. The standards do not move.

**Keep your own log.** Write down the date, the hours worked, the rate that was agreed. If the payroll ever does not match, you have the record. Most of the time you will never need it. The few times you do, you will be glad it exists.

## The T&T public holidays at a glance

These are the days the rule applies. Movable ones change each year.

- New Year's Day (1 January)
- Spiritual Shouter Baptist Liberation Day (30 March)
- Good Friday and Easter Monday (movable)
- Indian Arrival Day (30 May, today)
- Corpus Christi (movable)
- Labour Day (19 June)
- Emancipation Day (1 August)
- Independence Day (31 August)
- Republic Day (24 September)
- Christmas Day (25 December) and Boxing Day (26 December)
- Eid-ul-Fitr (movable, declared)
- Divali (movable, declared)
- Carnival Monday and Tuesday are not gazetted public holidays nationally, but most workplaces close. Treat them in your care arrangement the same way you treat the gazetted ones, or be explicit that you do not.

When a public holiday falls on a Sunday, the following Monday is observed in lieu. Indian Arrival Day 2026 falls on Saturday, so this year there is no Monday substitute, but the double-time rule still applies to anyone working today.

## Coverage patterns that hold up

A few patterns we have seen work across Trinidad and Tobago households.

**Primary plus one fill-in.** One main care professional, one named backup. The backup covers a planned share of the public holidays each year so the primary is not absorbing all of them.

**Weekend rotation built around the standard 8am to 4pm shift.** When public holidays land on weekends, the weekend shift covers them under the same double-time rule. No surprise scheduling.

**Live-in handover around the big festivals.** For households with live-in coverage, Divali, Eid, and Christmas are the times to plan the rotation handover, not the times to ask a single person to work straight through.

These are patterns, not products. The care rate stays where it is for ordinary days. Standard care is $40 per hour, Full Service is $45, Premium is $50 or more. The holiday rule doubles whichever rate applies. Your exact arrangement is shaped during onboarding.

## The globally minded part

Every country has these days. The names change. In Jamaica it is Emancipation Day in a different way. In the UK it is the bank holidays. In Canada it is Family Day. The names are local. The truth is universal: care does not pause for a holiday, the people doing the care deserve rest as much as anyone else, and coordination is the bridge between those two facts.

Trinidad and Tobago has written the rule into law. The job of a family and a care team is to honour it together, ahead of time, in writing.

## A note from Chanua

The first Indian Arrival Day I worked as a young care professional, I did not ask about the rate. I worked twelve hours straight, smiled at the family at the end of the shift, took home a flat rate, and cried in the maxi on the way home. Not because of the money. Because of how small I felt for not asking.

Years later, when I started Tavara, I made it part of the care arrangement that no care professional should ever have to ask. The double time is calculated automatically. The family knows. The care professional knows. Nobody has to negotiate the holiday.

If your household is not there yet, today is a fine day to start. Sit down this week. Mark the next twelve months of public holidays in red. Write one paragraph into your care arrangement. Then enjoy what is left of Indian Arrival Day, even if you are working through it, because somebody planned for you.

