When a caregiver starts shifts in your home, the house itself becomes part of the care. Not in a dramatic way. In the small, daily way a hallway is either clear or it is not. A bathroom either has a place to sit or it does not. A medication shelf either makes sense at 6am or it causes a mistake.

This is what we mean by home preparation. It is not cleaning. It is making the home work for the person being cared for, and for the care team that will be in and out of it.

## Why the home matters more than people expect

Families in Trinidad often focus on finding the right caregiver and forget that the room around the caregiver does half the work. A loved one who can reach a glass of water on her own keeps a small piece of independence. A bathroom with a steady grab bar prevents the fall that sends the whole family to Port of Spain General at 11pm. A clear hallway lets a caregiver move quickly when something changes.

When the home is ready, the care team can do real care. When the home is not ready, the care team spends the shift working around the house instead of with your loved one.

## The weekend walk-through any family can do

Before the first shift starts, walk through the home with the eyes of someone who has never lived there. Five things to look at.

**Airflow.** Open a window in the room where your loved one will spend most of the day. A breeze across the bed makes a long afternoon bearable in May heat. If the room only has one window, a small standing fan is a kindness.

**Hallway clearance.** Walk from the bedroom to the bathroom and from the bedroom to the kitchen. Move anything narrower than three feet of clear space. Rugs slip. Cords trip. Shoes by the door belong in a basket, not on the floor.

**Bathroom safety.** A grab bar near the toilet and one inside the shower. A non-slip mat. A plastic shower chair if standing for ten minutes is hard. None of this is expensive at Massy Stores or any pharmacy. All of it prevents the fall you are afraid of.

**Medication zone.** One shelf, one table, one labelled box. Not three bottles in the kitchen, two in the bedroom, and one in a handbag. A caregiver giving a 7am dose at the same place every morning makes fewer mistakes than a caregiver hunting through the house.

**Caregiver workspace.** A chair the caregiver can actually sit in during quiet hours. A small table for the daily log. A clear spot to charge a phone for the shift-end handoff. Treat the caregiver like a professional with a workstation, because that is what she is.

## Basic supplies the family provides

The caregiver brings her training. The family provides the supplies. A short list to start with.

- Disposable gloves, two boxes, kept where they are used
- A blood pressure cuff and a thermometer the family already trusts
- Clean towels and washcloths set aside for personal care, not shared with the rest of the household
- The week''s medications, sorted, in one place
- Food the loved one actually eats, labelled in the fridge so the caregiver does not have to guess
- A notebook for the daily log, in case the dashboard is not open

This list is not a shopping spree. Most families already own most of it. The work is putting it where the caregiver can find it without asking three questions.

## When to bring Tavara in

Some families do the walk-through, fix the small things over a weekend, and the home is ready. Other families look at the house and realise it needs more than one Saturday. A bedroom that has been a storage room for years. A bathroom that needs a real reset before a grab bar will hold. A garden gate that does not close.

When that is the situation, we coordinate the home preparation work for you. We have three levels.

**Care Readiness Assessment.** A walk-through with our coordinator who writes the list of what needs to happen, in what order, by when. You decide what you do yourself and what you want us to arrange.

**Guided Home Reset.** We bring in the vendors for the one-time work. Cleaning, small repairs, the grab bar install, the bedroom reset. You approve the scope, we manage the contractors, you do not chase anyone.

**Full Care Environment Reset.** For households that need ongoing coordination, not a one-time fix. Recurring pest control. Seasonal deep cleaning. Contractor management as the home and the care need both evolve.

Pricing for these three levels is shared privately during onboarding, because it depends on the size of the home and the scope of work. Contractor costs are billed directly to your family. Tavara coordinates and manages. We do not do the cleaning work ourselves, and we do not mark up the vendors.

## A note from Chanua

I started Tavara because I watched too many families bring a wonderful caregiver into a home that was not ready for her. Within a week, everyone was frustrated. The caregiver, because she could not do her job. The loved one, because the house felt strange. The family, because they could not understand why something they had paid for felt like it was not working.

Most of the time, it was the room. Not the caregiver. Not the loved one. The room.

Spend a Saturday on the walk-through. Fix the small things first. If the big things are too much for one weekend, call us and we will help you make a plan. The care goes better when the house is on your side.

