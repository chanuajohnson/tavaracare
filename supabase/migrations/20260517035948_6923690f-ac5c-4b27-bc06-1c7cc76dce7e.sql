A quick word on **GAPP**: it's a Ministry of Social Development and Family Services programme that places trained caregivers with qualifying households at no cost to the family. It's a real option and worth applying for. The trade-off is scope: GAPP placements follow a programme-defined brief, so the care is generally less curated to your specific household, less tailored to a spouse or secondary care need, and there is no private coordination layer sitting on top. Many families use GAPP as a foundation and layer private, household-specific support on top.

