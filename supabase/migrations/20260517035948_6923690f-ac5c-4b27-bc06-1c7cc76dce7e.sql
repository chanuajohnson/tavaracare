## The care coordination subscription

The subscription is where families sometimes pause, so let's be plain about what it is and what it isn't.

It is **not** the caregiver's pay. The caregiver is paid by the family directly, out of the per-hour care rate. Tavara is a care coordination platform, not the employer and not the payer. The subscription pays for the coordination layer that keeps care running smoothly across a small team:

- A shared dashboard for the family, the caregivers, and any nurses involved.
- Shift scheduling and shift swap cover when someone needs a day off.
- Daily care logs (meds, meals, mood, incidents) the whole family can see.
- Medication administration tracking with conflict checks.
- Payroll calculation and NIS reporting that we coordinate on the family's behalf. The family remains the engager of the caregiver; Tavara is not the employer.
- Care payment scheduling, we coordinate the timing and records on the family's behalf, the money flows family to caregiver.
- A coordinator (TAV, Tavara's care AI plus a human team) who notices when something looks off and nudges before it becomes a crisis.

**Basic (Free)** gets you a profile, a single caregiver match channel, and basic logs. Many families start here and never need more.

**Active Care** is for households running 30+ hours of care per week, the dashboard becomes the central operational tool. Most families with ongoing rotations land here. Tier pricing is shared at onboarding.

**Premium** adds extended coordination, proactive nudges, deeper analytics, environment support, priority response, and integration with the [Home Preparation](/about) tier. Tier pricing, and Home Preparation pricing, are quoted at onboarding based on scope.

You can downgrade or pause anytime. The subscription is meant to track the actual intensity of coordination, not lock you in.

