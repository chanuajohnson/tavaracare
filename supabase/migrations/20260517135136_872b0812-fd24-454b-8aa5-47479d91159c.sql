Most families call us hoping we can send someone tomorrow.

We understand the instinct. By the time a family reaches out, somebody is already exhausted. A parent has fallen, or stopped eating properly, or had a difficult night. The adult child has been holding it together for months and has finally hit the wall where one more invisible task will break something.

So when we say the first caregiver usually does not walk through the door for one to two weeks, it can feel like a delay. It is not. That window is the work that prevents everything families normally dread about arranging care.

This post walks through what actually happens during those two weeks, told through two real households we have walked beside. Both have been anonymised. No names, no addresses, no details that would let anyone recognise them.

## Step 1. The first conversation

The first thing we do is not match anyone to anything. We listen.

For a multi-generational household in central Trinidad coordinating care for an aging parent, the first conversation was about an hour long. The adult daughter did most of the talking. The father was managing on his own most days, but the mornings were getting harder, his medication was getting confused, and the daughter was driving across the country at lunchtime three days a week to check on him.

We were not taking notes on tasks. We were listening for the shape of the household. Who lives in the home. Who does not live there but carries the weight. What the parent's day used to look like and what it looks like now. Where the breakdowns are happening. Whether the family agrees on what is happening, because often they do not.

That conversation produces the first version of a care plan. Not a contract. A picture.

## Step 2. Mapping the household

Once we have the picture, we translate it into coverage.

For a Port-of-Spain family of three arranging continuous care for a parent with complex daily needs, mapping was the longest step. Their loved one needed help with mobility, medication, and overnight monitoring. The daughter was the one waking up at 2 AM to check on her mother and she had been doing it for almost a year.

Coverage for that household ended up looking like weekday daytime support, weekend daytime support, and an overnight rotation. That is three different shift shapes, which means more than one caregiver, which means a primary caregiver and fill-in caregivers who already know the home.

We do not present coverage like a menu. We present it like a plan. The family then tells us what is realistic for them right now and what they want to grow into. Some households start with weekday daytime and add weekends a month later, once everyone has adjusted. That is normal.

The per-hour care rate sits in three tiers. Standard at $40 per hour, Full Service at $45 per hour, Premium at $50 or more per hour, depending on the clinical scope. We talk about which tier fits the loved one's needs in this conversation, not in a quote at the end. The household decides what they can sustain.

## Step 3. The match

Now we choose a caregiver.

A match is not a search result. It is a small decision tree. Who is available for the shift shape this household needs. Who has worked with this kind of condition before. Whose temperament matches the household's temperament, because a quiet home and a loud home need different people in them.

The caregiver we matched to that Port-of-Spain household is a senior caregiver with two decades of bedside experience. She has worked in private homes, in hospital settings, and through long stretches with families who needed continuity more than anything else. She is calm. She does not perform. She arrives early and leaves on time. During an eight hour shift her personal phone stays away. That is not a Tavara rule we made up to sound strict. It is the professionalism standard we recruit for and the families feel it within the first week.

A primary caregiver is paired with fill-in caregivers who rotate through during weekends, holidays, or any week the primary is off. The fill-in caregivers are introduced to the home before they ever cover a shift alone. That is what makes the rotation feel like one care team instead of a series of strangers.

## Step 4. Home preparation

Before day one, the home itself changes.

Some of this is obvious. A safe path between the bedroom and the bathroom. A working light at the bedside. Medications labelled and stored in one place instead of three. Some of it is less obvious. A chair the caregiver can actually sit in during a long overnight shift. A space for the caregiver's bag that is not the family's dining table. A small set of supplies that should always be in the home and a quiet system for telling the family when they are running low.

Home preparation is a service, not a lecture. We can do it as a walk-through assessment, a guided reset alongside the family, or a full reset where our team handles it. Which version a household needs depends on how the home is functioning right now, not on what anyone is judging. Most homes need more help here than the family expects. That is not a moral failure. That is what happens when one person has been holding the whole household together for a year.

We never publish home preparation costs on the website. Those are discussed privately during onboarding because the right answer depends entirely on what the home actually needs.

## Step 5. Meet and greet

Now the caregiver and the family meet, in the home, with the loved one present.

This is not an interview. The match has already been made. The meet and greet is a calibration. The caregiver sees the home with her own eyes. The family hears how the caregiver talks to their loved one, which is the part you cannot tell from a profile. The loved one gets to be in the room while a decision is being made about them, which matters more than families sometimes realise.

We sit in on this visit when it helps. Sometimes the family wants us there as a translator between two different communication styles. Sometimes they prefer to host it themselves and tell us how it went afterwards. Either is fine.

If something feels off, we say so, and we re-match. That happens. Not often, but it happens, and a family that raises a quiet concern early gets a much better long term care team than a family that tries to be polite.

## Step 6. Service commencement

The first official shift is a signature day.

The family signs a service commencement agreement. The caregiver signs a baseline agreement that covers her scope of work, the household's preferences, and the no-personal-phone-during-shift standard. We confirm the loved one's daily rhythm in writing so it is not living only in the adult child's head anymore.

This is also the moment the dashboard becomes the operational hub of the care team. Care logs go in there. Medication administration goes in there. Shift swaps go in there. Family members who do not live in the home can finally see what is happening without phoning their sibling at 9 PM to ask how today went.

WhatsApp is the secondary channel. We use the central Tavara number, 1-868-786-5357, for handoffs and quick coordination. Anything that matters operationally also lives in the dashboard. That is the rule, and it is what keeps a care team from drifting back into chaos when people are tired.

## Step 7. The first two weeks of rotation

The primary caregiver settles in. The fill-in caregivers do their first covered shifts. Daily logs start accumulating.

By the end of the second week, the family is reading their loved one's days in writing for the first time. Breakfast eaten or not eaten. Medications administered, with timestamps. Mood, energy, mobility, any incident that needed attention. The adult child who was driving across the country at lunchtime stops driving across the country at lunchtime.

This is the quiet part of onboarding. It does not look dramatic. It looks like a phone that stops ringing at odd hours. It looks like a sibling group chat that calms down. It looks like the parent in the home being a little more like themselves, because the household around them is no longer in low-grade panic.

In the central Trinidad household, the daughter sent us a message at the end of week two that said only, "I slept eight hours last night." That is the metric.

## What onboarding prevents

Families who skip the careful version of this sequence usually end up living through what onboarding was designed to prevent.

Missed medications because nobody wrote down what was administered and the next person guessed.

Caregiver turnover because the match was made on availability instead of fit, and the caregiver left after three weeks.

Family arguments because nobody can tell who told who what, and the household is using three different communication channels with no record.

The slow drift back into crisis, which is the worst one, because it does not arrive as one big event. It arrives as a quiet erosion that the exhausted adult child does not have the bandwidth to notice until something breaks.

Onboarding is not a delay before the care starts. Onboarding is what makes the care sustainable.

## Closing

Tavara is a care coordination platform. We do not employ caregivers. The family arranges care directly with the caregiver, out of the per-hour care rate. What the platform provides is the coordination layer that keeps everything from sliding back into chaos. The intake. The matching. The home preparation. The dashboard. The care logs. The handoffs. The continuity when a primary caregiver takes a week off. The quiet, steady operational backbone underneath what looks, from the family's side, like a calm care team that just shows up.

If you are at the start of this and the idea of two weeks feels like a long time, that is usually a sign you have been carrying something alone for too long. Start the conversation. The first call is just listening.

