SET body = $body$Public holidays reveal whether a care arrangement is working.

The care does not pause for a holiday. The loved one still needs help getting out of bed. Medication still needs to be given. Meals still need to be prepared. Someone still needs to be there.

What changes is that public holidays force a household to answer questions that are easy to avoid the rest of the year.

Who is covering the shift? Does the care professional want to work that day? What happens if she wants to spend the holiday with her own family? What rate will apply? Can the household realistically afford it?

The hardest public holiday conversations are rarely about the holiday itself. They are usually about planning that never happened before the holiday arrived.

## The real conversation is operational

There are labour protections in Trinidad and Tobago that address work on public holidays, and any household coordinating care should be aware that these protections exist. We name them with families during onboarding so the context is clear.

But for most households, the more useful conversation is not legal. It is operational. A care arrangement works best when expectations are discussed ahead of time, documented clearly, and revisited before major holidays arrive.

## From the family side

You are not a bad family because you forgot the holiday was coming. Most families do. The fix is not guilt. The fix is planning.

**Plan two weeks ahead, not the night before.** Sit with your care team in the second week of every month and look at the next month's calendar. Mark the public holidays in red. Decide now who is covering each one.

A care professional who knows three weeks early that she is working Indian Arrival Day can plan her own family around it. A care professional who finds out the night before is being asked to sacrifice her holiday twice, once for your loved one and once for her own.

**Talk openly about compensation before the holiday arrives.** Some households pay time and a half. Some pay double time. Some arrange a substitute day off in the same week. Some rotate coverage between two care professionals so nobody works every holiday. What matters most is that the conversation happens early and that everyone understands the arrangement.

Surprises damage trust faster than almost anything else.

**Decide who covers when your main care professional wants the day off.** This is what a fill-in care professional is for. If your care arrangement has one person and no backup, the first public holiday will tell you. Build the rotation before you need it, not after.

**Mind the small dignities.** A plate of pelau from the family. A ride home after dark if shifts run long. A thank you that is spoken out loud, not just felt. These cost little and often matter more than people realise.

**Put the holiday arrangement in writing once.** One paragraph. How coverage is planned. How rates are handled. How swaps are agreed. Once expectations are written down, nobody has to renegotiate them every holiday.

## From the care professional side

Public holidays are easier when conversations happen before emotions enter the room.

**Ask early, not on the day.** If you know a holiday is coming, raise it during the planning conversation.

"I am happy to work the holiday. Can we talk about the coverage plan and compensation arrangement ahead of time?"

That is often enough.

**Understand the household's reality.** Not every family has unlimited resources. Many are balancing care costs, medications, medical appointments, home expenses, and their own household bills. The goal is not to win an argument. The goal is to find an arrangement that is fair, respectful, and sustainable.

**Professionalism still applies on the holiday.** The shift remains the shift. The standards remain the standards. The holiday may change the schedule, but it should not change the quality of care.

**Keep your own records.** Write down the date, hours worked, and what was agreed. Most of the time you will never need the notes. The few times you do, you will be glad they exist.

## A note on compensation

There is no single right answer. What households around Trinidad and Tobago actually do varies, and all of these are legitimate when agreed before the holiday:

- Time and a half on the shift worked
- Double time on the shift worked
- A substitute day off in the same week, paid at the usual care rate
- Rotating coverage between two care professionals so the load is shared

The rule is not which one. The rule is agree before, not after. Once the arrangement is set, write it down so the same conversation does not have to happen every holiday.

If a household cannot sustain double time across every public holiday in the year, that is honest information, not a failing. Bring it to the table early. A sustainable arrangement at a rate everyone agreed to is better than a generous arrangement that quietly breeds resentment.

## The 11 public holidays in Trinidad and Tobago

Mark these on your care calendar in January and revisit at the start of every month:

1. New Year's Day (1 January)
2. Spiritual Baptist Liberation Day (30 March)
3. Good Friday (varies)
4. Easter Monday (varies)
5. Indian Arrival Day (30 May)
6. Corpus Christi (varies)
7. Labour Day (19 June)
8. Emancipation Day (1 August)
9. Independence Day (31 August)
10. Republic Day (24 September)
11. Christmas Day and Boxing Day (25 and 26 December)

Eid ul Fitr and Divali also move each year. Treat them with the same planning even though the dates shift.

## The universal principle

This is not only a Trinidad and Tobago conversation. Anywhere in the world, families coordinating in-home care for a loved one face the same question on any culturally significant day. Christmas in Toronto. Eid in Manchester. Diwali in Mumbai. The country and the holiday change. The principle does not. Plan early, talk openly, write it down once, honour the people doing the work.

