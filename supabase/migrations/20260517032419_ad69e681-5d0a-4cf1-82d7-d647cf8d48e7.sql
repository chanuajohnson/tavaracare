## What "Standard," "Full Service," and "Premium" actually mean

Most agencies in T&T quote one rate and stay vague about scope. We split it into three tiers so families know exactly what they're paying for. Before we get into the Tavara tiers, a word on what sits below our floor.

### Market context: rates below the Tavara floor

Across T&T you'll see caregivers offered at under $30/hr, at $30/hr, and at $34/hr. These exist, and we want you to know what they typically signal so you can make an informed call.

**Under $30/hr** is usually an informal, unvetted arrangement. No background check, no coordination, no daily logs, no backup when the caregiver is sick. Common in friend-of-a-friend referrals. The risk sits entirely with the household.

**$30/hr** is entry-level companion care from independent caregivers or very small operators with minimal screening. Limited scope, often no medication training, no payroll handling, no NIS coordination on the family's behalf.

**$34/hr** is a basic agency rate. Some screening, some scheduling, but typically light on the operational layer that families actually need over time: shared dashboards, shift swap cover, daily care logs, payroll calculation, NIS reporting.

Tavara does not staff caregivers at these rates. Our floor is $40/hr because the rate covers a vetted caregiver plus the coordination layer the family doesn't have to build themselves. We list the lower rates for transparency, not as a comparison. They are different products at different price points.

### Standard ($40/hr)

Companion-level care. Conversation, light meal prep, light housekeeping in care areas, supervision, medication reminders (not administration), help getting around the house. Good for relatively independent seniors who mainly need company and a watchful eye.

### Full Service ($45/hr)

Hands-on personal care. Bathing, dressing, toileting, transfers, mobility assistance, structured meal prep, more involved housekeeping, accompaniment to appointments, medication administration where appropriate. This is what most families end up needing once a parent's mobility or cognition starts shifting.

### Premium ($50+/hr)

Clinical or specialised care. Dementia care with behavioural complexity, post-surgical recovery, wound care, catheter care, tube feeding, end-of-life care, anything requiring a nurse or specialist. The "+" matters, the rate goes up with the level of specialisation.

Caregivers move between tiers based on the scope of the assignment, not based on who they are as a person. Someone who is a Premium-tier nurse can take on a Standard companion shift; the rate reflects the work, not the person.

## What drives the price up

Four things, mainly:

**1. Hours per week.** A weekday-only daytime shift is one thing. Round-the-clock care with multiple caregivers in rotation is another. The hourly rate stays the same, but the weekly total moves fast.

**2. Complexity.** A diabetic parent with stable routines is a different operation from a parent with mid-stage dementia who wanders at night. Complexity often means a higher tier, a nurse instead of a caregiver assistant, and more handover time between shifts.

**3. Location and timing.** Holiday and overtime hours are billed at **1.5x** the standard rate, per Tavara's [escalation policy](/about). Weekend evenings, public holidays, and emergency call-outs all carry premium rates. This is industry-standard, not a Tavara quirk, but worth budgeting for.

**4. Household context and secondary care needs.** Pricing reflects the full picture of the home, not just the primary care recipient. A spouse who also needs check-ins, a second elder in the household, complex routines, dietary specifics, or layered medical conditions across more than one person all shape the caregiver brief. Curating to those specifics is part of what the rate pays for.

What does **not** drive Tavara pricing: family size, postcode, or how nice your house looks. The rate is the rate.

